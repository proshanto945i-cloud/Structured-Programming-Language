// EXAMPLE 1 : all comparison operators in C 

#include<stdio.h>
int main()
{
    int x=10;
    int y=5;

    printf("%d\n",x==y); // equal to operator 0
    printf("%d\n",x!=y); // not equal to operator 1
    printf("%d\n",x>y); // greater than operator 1
    printf("%d\n",x<y); // less than operator 0
    printf("%d\n",x>=y); // greater than or equal to operator 1
    printf("%d\n",x<=y); // less than or equal to operator 0

    return 0;
}
