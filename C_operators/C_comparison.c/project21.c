// EXAMPLE 2 

#include<stdio.h>
int main()
{
    int age = 20;

    printf("%d",age>18); // prints 1 because 20 is greater than 18
    printf("%d",age<18); // prints 0 because 20 is not less than 18
    printf("%d",age>=18); // prints 1 because 20 is greater than or equal to 18
    printf("%d",age<=18); // prints 0 because 20 is not less than or equal to 18

    return 0;
}
