// EXAMPLE 2 :increment and decrement operators in C

#include<stdio.h>
int main()
{
   int x=10;

   ++x; // increment operator 11 ; this will 1st increment the value of x and then return the value of x
    printf("%d\n",x);

   int y=10;
   
   --y; // decrement operator 9 ; this will 1st decrement the value of y and then return the value of y
    printf("%d\n",y);


    return 0;
}
